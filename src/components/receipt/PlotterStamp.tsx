"use client";

import { useEffect, useRef, useState } from "react";
import { generateStampSvg } from "@/lib/stamp";
import type { ReceiptPayload } from "@/lib/types";

/**
 * The stamp drawn by a "plotter": frame, title block, then APPROVED lands.
 * Same generator as the downloadable PNG, themed to the page and animated.
 * The finished drawing is the resting state; playing animates from blank.
 */
export function PlotterStamp({ payload, verifyUrl, autoPlay = true }: { payload: ReceiptPayload; verifyUrl: string; autoPlay?: boolean }) {
  const [svg, setSvg] = useState<string | null>(null);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    let alive = true;
    generateStampSvg({ payload, verifyUrl, themed: true }).then((s) => {
      if (alive) setSvg(s.replace(/^<\?xml[^>]*>\s*/, ""));
    });
    return () => {
      alive = false;
    };
  }, [payload, verifyUrl]);

  const play = () => {
    const el = ref.current;
    if (!el) return;
    el.classList.remove("playing");
    void el.offsetWidth;
    el.classList.add("playing");
  };

  useEffect(() => {
    if (svg && autoPlay) play();
  }, [svg, autoPlay]);

  return (
    <figure className="grid gap-2">
      <div
        ref={ref}
        className="plotter min-h-[120px]"
        // Generated by our own code from the signed payload; all values are escaped.
        dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
      />
      <figcaption className="flex flex-wrap items-center justify-between gap-2 text-sm text-[var(--ink-2)]">
        <span>
          {payload.demo?.sample
            ? "Sample demo on a bundled file. Not a credential."
            : "This is the stamp you send. Scan the code to verify the file."}
        </span>
        <button type="button" className="mono inline-flex min-h-11 items-center uppercase tracking-[0.08em] text-[var(--blueprint)] underline" onClick={play}>
          Replay
        </button>
      </figcaption>
    </figure>
  );
}
